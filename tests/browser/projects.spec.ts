import {test,expect,type Page} from '@playwright/test'
async function navigate(page:Page,role='Trainer'){
 await page.goto('/');await page.getByLabel('Preview as').selectOption(role)
 const menu=page.getByRole('button',{name:'Open navigation'});if(await menu.isVisible())await menu.click()
 await page.getByRole('navigation').getByRole('button',{name:'Projects',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Campus Connect',exact:true})).toBeVisible()
}
test('trainer creates and moves a task while arbitrary markup remains inert',async({page})=>{
 await navigate(page)
 await page.getByRole('button',{name:'New task',exact:true}).click()
 await page.getByLabel('Task title',{exact:true}).fill('Review the prototype')
 const source='<img src=x onerror="window.projectPwned=1">'
 await page.getByLabel('Task description',{exact:true}).fill(source)
 await page.getByRole('button',{name:'Save task',exact:true}).click()
 const card=page.locator('.project-task').filter({has:page.getByRole('heading',{name:'Review the prototype',exact:true})})
 await expect(card).toContainText(source)
 await card.getByLabel('Column for Review the prototype').selectOption('in_progress')
 await expect(page.locator('.project-column').filter({has:page.getByRole('heading',{name:'In progress',exact:false})})).toContainText('Review the prototype')
 expect(await page.evaluate(()=>(window as unknown as Record<string,unknown>).projectPwned)).toBeUndefined()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
})
test('mentor sees assigned progress and comments without task editing controls',async({page})=>{
 await navigate(page,'Mentor')
 await expect(page.getByRole('button',{name:'New task',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'Discussion and history: Map the student support journey',exact:true}).click()
 await page.getByLabel('Project comment',{exact:true}).fill('A useful next step: test the first prototype.')
 await page.getByRole('button',{name:'Post comment',exact:true}).click()
 await expect(page.locator('.project-comment')).toContainText('test the first prototype')
})
test('sprint close preserves unfinished tasks and explicit reason is required',async({page})=>{
 await navigate(page)
 await page.getByRole('button',{name:'Plan a sprint',exact:true}).click()
 await page.getByLabel('Sprint title',{exact:true}).fill('Prototype sprint')
 await page.getByLabel('Sprint goal',{exact:true}).fill('Build and review a simple flow')
 await page.getByLabel('Sprint starts (your local time)',{exact:true}).fill('2027-04-01T09:00')
 await page.getByLabel('Sprint ends (your local time)',{exact:true}).fill('2027-04-08T09:00')
 await page.getByRole('button',{name:'Save sprint plan',exact:true}).click()
 await expect(page.getByRole('button',{name:'Start Prototype sprint',exact:true})).toBeDisabled()
 await page.getByLabel('Action reason',{exact:true}).fill('Team ready to begin')
 await page.getByRole('button',{name:'Start Prototype sprint',exact:true}).click()
 await page.getByLabel('Action reason',{exact:true}).fill('Review unfinished work')
 await page.getByRole('button',{name:'Close Prototype sprint',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Prototype sprint · closed',exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Map the student support journey',exact:true})).toBeVisible()
})
test('organizer explicitly configures capacities and archive retains read-only history',async({page})=>{
 await navigate(page,'Organizer')
 await page.getByRole('button',{name:'Edit project setup',exact:true}).click()
 await page.getByLabel('Project title',{exact:true}).fill('Updated sample project')
 await page.getByLabel('participant capacity',{exact:true}).fill('12')
 await page.getByRole('button',{name:'Save project setup',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Updated sample project',exact:true})).toBeVisible()
 await page.getByLabel('Action reason',{exact:true}).fill('Project demonstration is complete')
 await page.getByRole('button',{name:'Archive project as read-only',exact:true}).click()
 await expect(page.getByText('This project is read-only.',{exact:false})).toBeVisible()
 await expect(page.getByRole('button',{name:'New task',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'Discussion and history: Map the student support journey',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Change history',exact:true})).toBeVisible()
})
