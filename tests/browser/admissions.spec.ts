import {test,expect} from '@playwright/test'
test('sample application issues a private receipt and checks status',async({page})=>{
 await page.goto('/')
 const menu=page.getByRole('button',{name:'Open navigation'});if(await menu.isVisible())await menu.click()
 await page.getByRole('navigation').getByRole('button',{name:'Admissions'}).click()
 await page.getByLabel('Full name',{exact:true}).fill('Synthetic Browser Applicant')
 await page.getByLabel('Email',{exact:true}).fill('synthetic@example.test')
 await page.getByLabel('What would you like to learn through Next-Gen?').fill('Prepare for year two')
 await page.getByRole('button',{name:'Try sample application'}).click()
 await expect(page.getByRole('heading',{name:'Keep your private receipt.'})).toBeVisible()
 await page.locator('.receipt-panel').getByRole('button',{name:'Check status',exact:false}).click()
 await page.locator('.application-form').getByRole('button',{name:'Check status',exact:false}).click()
 await expect(page.getByRole('status').filter({hasText:'Application status: submitted'})).toBeVisible()
})
test('review preview cannot skip review and requires an outcome note',async({page})=>{
 await page.goto('/');await page.getByLabel('Preview as').selectOption('Organizer')
 const menu=page.getByRole('button',{name:'Open navigation'});if(await menu.isVisible())await menu.click()
 await page.getByRole('navigation').getByRole('button',{name:'Admissions'}).click()
 await page.getByRole('button',{name:'Review queue',exact:true}).click()
 await page.getByRole('button').filter({hasText:'Alex Demo'}).click()
 await expect(page.getByRole('button',{name:'Start review',exact:true})).toBeDisabled()
 await page.getByLabel('Review note / outcome evidence').fill('Interview review started')
 await page.getByRole('button',{name:'Start review',exact:true}).click()
 await page.getByLabel('Review note / outcome evidence').fill('Interview pass verified')
 await page.getByRole('button',{name:'Record interview passed'}).click()
 await expect(page.getByRole('status').filter({hasText:'interview passed'})).toBeVisible()
})
